type IconName = keyof typeof icons

function Icon({ name, size = 16 }: { name: IconName; size?: number }) {
  const Glyph = icons[name]
  return (
    <span data-kit="icon" data-icon={name} aria-hidden>
      <Glyph size={size} />
    </span>
  )
}

